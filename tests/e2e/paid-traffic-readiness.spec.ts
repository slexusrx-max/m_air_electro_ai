import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { catalog } from "../../lib/affiliate/catalog";
import { expectSupplierCta } from "../supplier-link-expectations";

for (const locale of ["ro", "en"]) for (const width of [390, 430]) {
  test(`mobile calculator to supplier handoff ${locale} ${width}`, async ({ page, context, baseURL }, info) => {
    const prefix = locale === "en" ? "/en" : "";
    const origin = new URL(baseURL!).origin;
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.setViewportSize({ width, height: 844 });
    // No affiliate-network request or merchant order is generated by this journey.
    await context.route("**/*", route => {
      if (route.request().isNavigationRequest() && new URL(route.request().url()).origin !== origin) {
        return route.fulfill({ contentType: "text/html", body: "<title>Intercepted supplier handoff</title>" });
      }
      return route.continue();
    });
    await page.goto(`${prefix}/`);
    const homeUrl = page.url();
    const calculator = page.getByTestId("quick-solution-starter");
    await calculator.getByLabel(locale === "ro" ? "Consum simultan în wați" : "Running load in watts", { exact: true }).fill("300");
    await expect(page).toHaveURL(homeUrl);
    await expect(calculator.locator(".quick-solution-result")).toContainText(locale === "ro" ? "VERIFICĂ DATELE" : "CHECK YOUR INPUTS");
    await calculator.getByLabel(locale === "ro" ? "Vârf la pornire în wați" : "Starting peak in watts", { exact: true }).fill("600");
    await expect(calculator.locator(".quick-solution-result")).toContainText("1200 Wh");
    await calculator.locator(".button-primary").click();
    await expect(page).toHaveURL(/find-my-solution\?.*load=300/);
    await page.getByRole("button", { name: locale === "ro" ? "Calculează sistemul" : "Calculate system", exact: true }).click();
    await expect(page.locator(".finder-results")).toContainText("300 W");
    await expect(page.locator('[data-recommendation="best"]')).toHaveCount(1);
    expect(await page.locator(".finder-results .equipment-card").count()).toBeGreaterThan(1);
    await expect(page.locator('[data-price-status="fresh"]')).toHaveCount(0);
    const noOverflow = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await noOverflow();
    const a11y = await new AxeBuilder({ page }).include(".finder-results").withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze();
    expect(a11y.violations).toEqual([]);
    await page.locator('.finder-results a[href*="/compare?ids="]').click();
    await expect(page.locator(".comparison-scroll table")).toBeVisible();
    await noOverflow();
    const supplier = page.locator(".comparison-scroll [data-supplier-product]").first();
    const id = await supplier.getAttribute("data-supplier-product");
    const matchedProduct = catalog.find(item => item.id === id)!;
    await expectSupplierCta(supplier, matchedProduct, new URL(baseURL!).hostname === "mairelectroai.com");
    const destination = (await supplier.getAttribute("href"))!;
    const popupPromise = context.waitForEvent("page");
    await supplier.click();
    const popup = await popupPromise;
    await expect(popup).toHaveURL(destination);
    await expect(popup).toHaveTitle("Intercepted supplier handoff");
    await popup.close();
    await page.screenshot({ path: info.outputPath(`purchase-${locale}-${width}.png`) });
    expect(errors).toEqual([]);
  });
}

test("Romanian battery advertising landing keeps a usable mobile supplier path", async ({ page, baseURL }, info) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const response = await page.goto("/marketplace/batteries?utm_source=google&utm_medium=cpc&utm_campaign=ro_battery_pilot_20261028");
  expect(response?.status()).toBe(200);
  await expect(page.locator("html")).toHaveAttribute("lang", "ro");
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute("href", "https://mairelectroai.com/marketplace/batteries");
  const supplier = page.locator('main [data-supplier="renogy"]').first();
  const productId = await supplier.getAttribute("data-supplier-product");
  const product = catalog.find(item => item.id === productId);
  expect(product).toBeDefined();
  await expectSupplierCta(supplier, product!, new URL(baseURL!).hostname === "mairelectroai.com");
  await supplier.scrollIntoViewIfNeeded();
  await expect(supplier).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  expect((await new AxeBuilder({ page }).include("main").withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: info.outputPath("ro-ad-landing.png") });
});
